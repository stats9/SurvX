"""Writes dev/API_MAP.md: every compiled entry point, the C API function it wraps and the R files
that call it. Run from the package root: python3 dev/api_map.py"""
import glob, os, re

src = open("src/rwrap.cpp").read()
wrap = {}
for m in re.finditer(r"void (SX_\w+)\(([^)]*)\)\s*\{(.*?)\n\}", src, re.S):
    calls = sorted(set(re.findall(r"\b(sc_\w+)\(", m.group(3))) - {"sc_fit_info"})
    wrap[m.group(1)] = calls
callers = {k: [] for k in wrap}
for f in sorted(glob.glob("R/*.R")):
    s = open(f).read()
    for k in wrap:
        if re.search(r'"%s"' % k, s):
            callers[k].append(os.path.basename(f))
api = re.findall(r"^\w[\w\s\*]*?\b(sc_\w+)\(", open("src/survcore/survcore.h").read(), re.M)
used = {c for v in wrap.values() for c in v}
out = ["# Compiled entry points and their R callers", "",
       "Generated by `dev/api_map.py` from `src/rwrap.cpp`, `src/survcore/survcore.h` and `R/*.R`; do not edit by hand.", "",
       "| R entry point (`.C`) | C API (`survcore.h`) | called from |", "| --- | --- | --- |"]
for k in sorted(wrap):
    out.append("| `%s` | %s | %s |" % (k, ", ".join("`%s`" % c for c in wrap[k]) or "-", ", ".join(callers[k]) or "**not called**"))
out += ["", "C API functions without an R wrapper (used by other entry points, tests or other languages): " +
        (", ".join("`%s`" % a for a in sorted(set(api) - used)) or "none") + "."]
open("dev/API_MAP.md", "w").write("\n".join(out) + "\n")
print(len(wrap), "wrappers,", len(set(api)), "C API functions")
